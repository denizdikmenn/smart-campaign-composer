-- Delivery records (contract for the delivery pipeline): one row per
-- recipient and channel with the resolved content and its origin, so
-- monitoring can break results down by variant, group and language.
-- Assignment is resolved once when rows are created; retries only bump attempts.
CREATE TABLE IF NOT EXISTS deliveries (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id      bigint      NOT NULL REFERENCES campaigns (id) ON DELETE CASCADE,
    customer_id      bigint      NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    channel          text        NOT NULL CHECK (channel IN ('sms', 'email')),
    variant_position integer     CHECK (variant_position BETWEEN 1 AND 3),
    group_position   integer     CHECK (group_position BETWEEN 0 AND 9),
    language         text        NOT NULL,
    content_source   text        NOT NULL CHECK (content_source IN ('template', 'group', 'individual', 'fallback')),
    subject          text        NOT NULL DEFAULT '',
    body             text        NOT NULL,
    status           text        NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'sending', 'sent', 'delivered', 'failed')),
    attempts         integer     NOT NULL DEFAULT 0,
    last_error       text,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE (campaign_id, customer_id, channel)
);

CREATE INDEX IF NOT EXISTS deliveries_campaign_status_idx ON deliveries (campaign_id, status);
-- Set when the marketer confirmed "Apply to all" for individual personalization.
ALTER TABLE campaigns ADD COLUMN IF NOT EXISTS individual_applied_at timestamptz;

-- Delivery pipeline. dispatched_at is set once, in the transaction that
-- creates the campaign's delivery jobs (Send).
ALTER TABLE campaigns ADD COLUMN IF NOT EXISTS dispatched_at timestamptz;

-- deliveries is also the queue: the worker claims due rows with
-- FOR UPDATE SKIP LOCKED and holds a lease (locked_until) while sending.
-- 'delivered' is not used: mock providers only report acceptance.
ALTER TABLE deliveries DROP CONSTRAINT IF EXISTS deliveries_status_check;
ALTER TABLE deliveries ADD CONSTRAINT deliveries_status_check
    CHECK (status IN ('queued', 'sending', 'retrying', 'sent', 'failed', 'skipped'));
ALTER TABLE deliveries ADD COLUMN IF NOT EXISTS next_attempt_at timestamptz NOT NULL DEFAULT now();
ALTER TABLE deliveries ADD COLUMN IF NOT EXISTS locked_until timestamptz;
ALTER TABLE deliveries ADD COLUMN IF NOT EXISTS sent_at timestamptz;
ALTER TABLE deliveries ADD COLUMN IF NOT EXISTS provider_message_id text;
CREATE INDEX IF NOT EXISTS deliveries_due_idx ON deliveries (channel, next_attempt_at)
    WHERE status IN ('queued', 'retrying', 'sending');

-- The mock providers' own idempotency store, standing in for the key store a
-- real provider keeps on its side: a key is accepted at most once, ever.
CREATE TABLE IF NOT EXISTS mock_provider_messages (
    idempotency_key text        PRIMARY KEY,
    channel         text        NOT NULL,
    message_id      text        NOT NULL,
    accepted_at     timestamptz NOT NULL DEFAULT now()
);

-- Liveness of delivery workers, shown in monitoring.
CREATE TABLE IF NOT EXISTS worker_heartbeats (
    name    text        PRIMARY KEY,
    seen_at timestamptz NOT NULL
);

-- Delivery details: provider code of the last attempt, whether a failure is a
-- permanent rejection (never retryable), and the attempt count at the last
-- manual retry (a manual retry starts a new round of up to 4 attempts).
ALTER TABLE deliveries ADD COLUMN IF NOT EXISTS last_code text;
ALTER TABLE deliveries ADD COLUMN IF NOT EXISTS permanent boolean NOT NULL DEFAULT false;
ALTER TABLE deliveries ADD COLUMN IF NOT EXISTS retry_base integer NOT NULL DEFAULT 0;
CREATE INDEX IF NOT EXISTS deliveries_campaign_id_idx ON deliveries (campaign_id, id);

-- One row per provider call (consent skips make no call and have none).
-- A resumed attempt after a worker crash repeats its attempt number.
CREATE TABLE IF NOT EXISTS delivery_attempts (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id bigint      NOT NULL REFERENCES deliveries (id) ON DELETE CASCADE,
    attempt     integer     NOT NULL,
    started_at  timestamptz NOT NULL,
    latency_ms  integer     NOT NULL,
    http_status integer,                -- NULL: no response
    code        text,                   -- provider code, or NO_RESPONSE
    outcome     text        NOT NULL,   -- sent | retrying | failed
    error       text,
    message_id  text,
    manual      boolean     NOT NULL DEFAULT false  -- first attempt after a manual retry
);
CREATE INDEX IF NOT EXISTS delivery_attempts_delivery_idx ON delivery_attempts (delivery_id, id);
