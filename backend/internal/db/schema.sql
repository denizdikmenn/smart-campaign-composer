-- Idempotent schema: safe to run on every startup.

CREATE TABLE IF NOT EXISTS customers (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name    text        NOT NULL CHECK (first_name <> ''),
    last_name     text        NOT NULL CHECK (last_name <> ''),
    email         text        NOT NULL UNIQUE
                  CHECK (email = lower(email) AND email ~ '^[^@[:space:]]+@[^@[:space:]]+$'),
    -- E.164. Nullable: not every customer has given us a phone number.
    phone         text        UNIQUE CHECK (phone ~ '^\+[1-9][0-9]{7,14}$'),
    city          text        NOT NULL CHECK (city <> ''),
    -- Preferred content language (ISO 639-1), for message generation.
    language      text        NOT NULL DEFAULT 'tr' CHECK (language ~ '^[a-z]{2}$'),
    -- Consent is tracked per channel and defaults to "not consented".
    email_consent boolean     NOT NULL DEFAULT false,
    sms_consent   boolean     NOT NULL DEFAULT false,
    created_at    timestamptz NOT NULL DEFAULT now(),
    -- Last visit, cart or purchase. Visits are not stored as events, so this is a column.
    last_active_at timestamptz NOT NULL DEFAULT now(),
    -- SMS consent is meaningless (and unsafe) without a number to send to.
    CHECK (NOT sms_consent OR phone IS NOT NULL)
);

-- Upgrade path for databases created before these columns existed.
ALTER TABLE customers ADD COLUMN IF NOT EXISTS language text NOT NULL DEFAULT 'tr' CHECK (language ~ '^[a-z]{2}$');
ALTER TABLE customers ADD COLUMN IF NOT EXISTS last_active_at timestamptz NOT NULL DEFAULT now();

CREATE INDEX IF NOT EXISTS customers_city_idx ON customers (city);

-- Purchases. Amounts are in the store currency (TRY).
CREATE TABLE IF NOT EXISTS orders (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  bigint        NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    category     text          NOT NULL CHECK (category <> ''),
    total_amount numeric(10,2) NOT NULL CHECK (total_amount > 0),
    placed_at    timestamptz   NOT NULL
);

CREATE INDEX IF NOT EXISTS orders_customer_placed_idx ON orders (customer_id, placed_at);

-- "Added to cart" events, kept separate from orders so that
-- "added to cart but did not purchase since" can be expressed.
CREATE TABLE IF NOT EXISTS cart_additions (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint      NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    category    text        NOT NULL CHECK (category <> ''),
    added_at    timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS cart_additions_customer_added_idx ON cart_additions (customer_id, added_at);
CREATE INDEX IF NOT EXISTS cart_additions_added_idx ON cart_additions (added_at);

-- One row per AI audience suggestion request: input, raw LLM output, validated
-- result, timings and tokens. For debugging and future evaluations.
CREATE TABLE IF NOT EXISTS segmentation_runs (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    timestamptz NOT NULL DEFAULT now(),
    brief         text        NOT NULL,
    source        text        NOT NULL,              -- 'claude' | 'mock'
    model         text,
    status        text        NOT NULL,              -- ok | no_valid | refusal | auth_error | unavailable | bad_reply | error
    error         text,
    llm_ms        integer,                           -- Claude call only
    total_ms      integer     NOT NULL,              -- whole request
    input_tokens  integer,
    output_tokens integer,
    raw_output    text,                              -- raw model JSON, capped (untrusted)
    alternatives  jsonb       NOT NULL DEFAULT '[]', -- final validated results incl. counts
    warnings      jsonb       NOT NULL DEFAULT '[]'  -- dropped alternatives and why
);

CREATE INDEX IF NOT EXISTS segmentation_runs_created_idx ON segmentation_runs (created_at DESC);

-- Outcome classification (supported / needs_clarification / unsupported / invalid)
-- and the model's user-facing assessment (message, questions, ...).
ALTER TABLE segmentation_runs ADD COLUMN IF NOT EXISTS outcome text;
ALTER TABLE segmentation_runs ADD COLUMN IF NOT EXISTS assessment jsonb;

-- Campaigns: brief + selected audience rules, and the approval record.
-- approved_snapshot is the exact content and audience that was approved.
CREATE TABLE IF NOT EXISTS campaigns (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    brief             text        NOT NULL CHECK (brief <> ''),
    audience          jsonb       NOT NULL,
    status            text        NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'approved')),
    approved_version  integer,
    approved_at       timestamptz,
    approved_snapshot jsonb,
    CHECK ((status = 'approved') = (approved_at IS NOT NULL AND approved_version IS NOT NULL AND approved_snapshot IS NOT NULL))
);

-- Draft versions (Draft 1, 2, ...). A regeneration adds a row; edits update
-- the row being edited. Never modified once the campaign is approved.
CREATE TABLE IF NOT EXISTS campaign_drafts (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id   bigint      NOT NULL REFERENCES campaigns (id) ON DELETE CASCADE,
    version       integer     NOT NULL CHECK (version > 0),
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    source        text        NOT NULL,              -- 'claude' | 'mock'
    feedback      text        NOT NULL DEFAULT '',   -- feedback that produced this draft
    sms_enabled   boolean     NOT NULL,
    email_enabled boolean     NOT NULL,
    settings      jsonb       NOT NULL,
    sms_body      text        NOT NULL,
    email_subject text        NOT NULL,
    email_body    text        NOT NULL,
    UNIQUE (campaign_id, version)
);

-- One row per content generation request (success or failure): inputs,
-- raw model output, tokens and timings. Like segmentation_runs.
CREATE TABLE IF NOT EXISTS content_runs (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    timestamptz NOT NULL DEFAULT now(),
    campaign_id   bigint      NOT NULL REFERENCES campaigns (id) ON DELETE CASCADE,
    from_version  integer,                            -- base draft; NULL for the first draft
    draft_version integer,                            -- created draft; NULL on failure
    source        text        NOT NULL,
    model         text,
    status        text        NOT NULL,               -- ok | canceled | refusal | auth_error | unavailable | bad_reply | error
    error         text,
    llm_ms        integer,
    total_ms      integer     NOT NULL,
    input_tokens  integer,
    output_tokens integer,
    input         jsonb       NOT NULL DEFAULT '{}',  -- settings, feedback, channel flags (no secrets)
    raw_output    text                                -- capped, untrusted
);

CREATE INDEX IF NOT EXISTS content_runs_campaign_idx ON content_runs (campaign_id, id DESC);

