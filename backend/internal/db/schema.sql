ALTER TABLE campaign_drafts ADD COLUMN IF NOT EXISTS parent_version integer;
-- Language of the draft's own fields; translations hold the other languages:
-- {"en": {"sms_body", "email_subject", "email_body", "base_hash"}}.
ALTER TABLE campaign_drafts ADD COLUMN IF NOT EXISTS language text NOT NULL DEFAULT 'tr';
ALTER TABLE campaign_drafts ADD COLUMN IF NOT EXISTS translations jsonb NOT NULL DEFAULT '{}';

ALTER TABLE campaigns ADD COLUMN IF NOT EXISTS personalization text NOT NULL DEFAULT 'standard'
    CHECK (personalization IN ('standard', 'groups', 'individual'));
-- Draft used by Standard approval and as the base for groups / individual.
ALTER TABLE campaigns ADD COLUMN IF NOT EXISTS selected_version integer;
-- Outcome of the last behavioral grouping proposal: {outcome, message, warnings}.
ALTER TABLE campaigns ADD COLUMN IF NOT EXISTS groups_note jsonb;

-- Active A/B variants (2-3 while enabled; none = no experiment). Label = A/B/C by position.
CREATE TABLE IF NOT EXISTS campaign_variants (
    campaign_id   bigint  NOT NULL REFERENCES campaigns (id) ON DELETE CASCADE,
    position      integer NOT NULL CHECK (position BETWEEN 1 AND 3),
    draft_version integer NOT NULL,
    PRIMARY KEY (campaign_id, position),
    UNIQUE (campaign_id, draft_version)
);

-- Behavioral groups of a campaign's audience. Position 0 is the remainder
-- ("everyone else"); 1..9 are rule groups, first match wins.
CREATE TABLE IF NOT EXISTS campaign_groups (
    campaign_id bigint      NOT NULL REFERENCES campaigns (id) ON DELETE CASCADE,
    position    integer     NOT NULL CHECK (position BETWEEN 0 AND 9),
    name        text        NOT NULL,
    description text        NOT NULL DEFAULT '',
    match       text        NOT NULL DEFAULT 'all',
    conditions  jsonb       NOT NULL DEFAULT '[]',
    size        integer     NOT NULL DEFAULT 0,
    languages   jsonb       NOT NULL DEFAULT '{}',   -- reachable members per content language
    content     jsonb       NOT NULL DEFAULT '{}',   -- {lang: {sms_body, email_subject, email_body, base_hash}}
    status      text        NOT NULL DEFAULT 'proposed' CHECK (status IN ('proposed', 'generating', 'generated', 'failed')),
    error       text,
    updated_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (campaign_id, position)
);

-- Individually generated messages (Individual personalization).
CREATE TABLE IF NOT EXISTS personalized_messages (
    campaign_id   bigint      NOT NULL REFERENCES campaigns (id) ON DELETE CASCADE,
    customer_id   bigint      NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    language      text        NOT NULL,
    status        text        NOT NULL CHECK (status IN ('pending', 'generated', 'fallback', 'failed')),
    sms_body      text        NOT NULL DEFAULT '',
    email_subject text        NOT NULL DEFAULT '',
    email_body    text        NOT NULL DEFAULT '',
    reason        text        NOT NULL DEFAULT '',  -- why fallback / failed
    base_hash     text        NOT NULL DEFAULT '',  -- base draft it was written from
    input_tokens  integer     NOT NULL DEFAULT 0,
    output_tokens integer     NOT NULL DEFAULT 0,
    updated_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (campaign_id, customer_id)
);

CREATE INDEX IF NOT EXISTS personalized_messages_status_idx ON personalized_messages (campaign_id, status);

